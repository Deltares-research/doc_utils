"""Remove LaTeX build artifacts (``.aux``, ``.log``, ``.bbl``, ...) from a directory.

Backs the ``ddocs clean`` command. This is independent of the Markdown-to-LaTeX
conversion -- it only deletes the throwaway files a LaTeX/BibTeX run leaves behind and,
when asked (``--templates``), the Deltares template files that ``ddocs get-tex-template``
downloads next to the document.
"""

import argparse
import re
import warnings
from pathlib import Path

from ddocs.latex.template_files import TEMPLATE_PICTURES, TEMPLATE_PICTURES_DIR

# LaTeX build file extensions removed by default.
LATEX_BUILD_EXTENSIONS: tuple[str, ...] = (
    ".aux",  # Auxiliary file
    ".log",  # Log file
    ".bbl",  # Bibliography file (bibtex output)
    ".blg",  # Bibliography log file
    ".bcf",  # biblatex control file
    ".toc",  # Table of contents
    ".lof",  # List of figures
    ".lot",  # List of tables
    ".lol",  # List of listings
    ".loe",  # List of exercises
    ".tdo",  # todonotes list
    ".fdb_latexmk",  # latexmk file database
    ".fls",  # File list (latex -recorder)
    ".synctex.gz",  # SyncTeX file
    ".out",  # Hyperref outline
    ".nav",  # Beamer navigation
    ".snm",  # Beamer slide notes
    ".vrb",  # Beamer verbatim
    ".idx",  # Index file
    ".ilg",  # Index log
    ".ind",  # Index output
    ".xdy",  # xindy index style
    ".nlo",  # nomencl nomenclature list
    ".nls",  # nomencl sorted nomenclature
    ".nlg",  # nomencl log
    ".glo",  # glossary list
    ".gls",  # glossary output
    ".glg",  # glossary log
    ".maf",  # minitoc auxiliary file list
    ".mtc",  # minitoc mini table of contents
)

# minitoc writes one numbered file per mini table of contents: .mtc0, .mtc1, ...
_MINITOC_NUMBERED = re.compile(r"\.mtc\d+$")

# Files fetched by ``ddocs get-tex-template`` (Deltares classes, styles, bib and makeindex styles).
TEMPLATE_FILE_PATTERNS: tuple[str, ...] = (
    "deltares_*.cls",
    "deltares_*.sty",
    "deltares_*.bst",
    "deltares_*.ist",
)


def _is_build_file(path: Path) -> bool:
    """Return True when `path` is a regular file with a LaTeX build-artifact extension."""
    name = path.name.lower()
    return path.is_file() and (name.endswith(LATEX_BUILD_EXTENSIONS) or _MINITOC_NUMBERED.search(name) is not None)


def _remove_file(file_path: Path, directory: Path) -> int:
    """Delete one file, report it, and return 1 on success or 0 when it could not be removed."""
    try:
        file_path.unlink()
        print(f"Removed: {file_path.relative_to(directory)}")
        removed = 1
    except OSError as e:
        print(f"Warning: Could not remove {file_path}: {e}")
        removed = 0
    return removed


def _remove_template_pictures(pictures_dir: Path, directory: Path) -> int:
    """Delete the downloaded template pictures from `pictures_dir` and keep everything else.

    Only the files listed in :data:`ddocs.latex.template_files.TEMPLATE_PICTURES` are removed. The directory
    itself is removed only when it is empty afterwards; otherwise the remaining files are reported and kept.

    Returns:
        Number of items removed: the picture files, plus one when the emptied folder itself was removed.
    """
    removed = 0
    for name in TEMPLATE_PICTURES:
        picture = pictures_dir / name
        if picture.is_file():
            removed += _remove_file(picture, directory)

    remaining = list(pictures_dir.iterdir())
    relative = pictures_dir.relative_to(directory)
    if remaining:
        print(f"Kept: {relative}/ ({len(remaining)} item(s) that are not template pictures)")
    else:
        try:
            pictures_dir.rmdir()
            print(f"Removed: {relative}/")
            removed += 1
        except OSError as e:
            print(f"Warning: Could not remove {pictures_dir}: {e}")
    return removed


def clean_latex_build_files(
    directory: Path,
    pattern: str | None = None,
    templates: bool = False,
    recursive: bool | None = None,
) -> int:
    """Clean LaTeX build artifacts (and optionally downloaded templates) from a directory.

    Removes the files generated by pdflatex, bibtex, makeindex, minitoc, nomencl and
    related tools -- see :data:`LATEX_BUILD_EXTENSIONS` -- plus numbered ``.mtcN`` files.
    Source files (``.tex``) and the produced ``.pdf`` are never touched. File extensions are matched
    case-insensitively on every platform, so ``DOC.AUX`` is treated like ``doc.aux``.

    Args:
        directory: Directory to clean
        pattern: Deprecated, use `recursive`. ``"**/*"`` meant recursive and any other value meant
            non-recursive. Passing it emits a :class:`DeprecationWarning`; `recursive` takes precedence when
            both are given.
        templates: When True, also remove the files ``ddocs get-tex-template`` downloads:
            ``deltares_*.cls/.sty/.bst/.ist`` and the template pictures in ``pictures/``, both looked up
            directly in `directory` only (never in subdirectories, even for a recursive clean). Only the
            known template pictures are removed from ``pictures/``; any other file you put there is kept, and
            the directory is removed only when it ends up empty. Defaults to False.
        recursive: Clean subdirectories too (True) or only `directory` itself (False). Defaults to True, which
            is also what applies when neither `recursive` nor `pattern` is given.

    Returns:
        Number of items removed: files, plus one for each emptied ``pictures/`` folder that was deleted.

    Warns:
        DeprecationWarning: If the deprecated `pattern` argument is passed.

    Examples:
        - Remove the build artifacts next to a document:
            ```python
            >>> import tempfile
            >>> from pathlib import Path
            >>> from ddocs.latex.clean import clean_latex_build_files
            >>> with tempfile.TemporaryDirectory() as tmp:
            ...     (Path(tmp) / "doc.tex").touch()
            ...     (Path(tmp) / "doc.aux").touch()
            ...     clean_latex_build_files(Path(tmp), recursive=False)
            Removed: doc.aux
            1

            ```
        - Source files and the PDF are kept; minitoc and nomencl artifacts are removed:
            ```python
            >>> import tempfile
            >>> from pathlib import Path
            >>> from ddocs.latex.clean import clean_latex_build_files
            >>> with tempfile.TemporaryDirectory() as tmp:
            ...     for name in ["doc.tex", "doc.pdf", "doc.mtc0", "doc.nls"]:
            ...         (Path(tmp) / name).touch()
            ...     count = clean_latex_build_files(Path(tmp), recursive=False)
            ...     sorted(p.name for p in Path(tmp).iterdir())
            Removed: doc.mtc0
            Removed: doc.nls
            ['doc.pdf', 'doc.tex']

            ```
        - Also remove the files downloaded by ``ddocs get-tex-template``:
            ```python
            >>> import tempfile
            >>> from pathlib import Path
            >>> from ddocs.latex.clean import clean_latex_build_files
            >>> with tempfile.TemporaryDirectory() as tmp:
            ...     (Path(tmp) / "deltares_report.cls").touch()
            ...     (Path(tmp) / "mystyle.sty").touch()
            ...     count = clean_latex_build_files(Path(tmp), templates=True, recursive=False)
            ...     sorted(p.name for p in Path(tmp).iterdir())
            Removed: deltares_report.cls
            ['mystyle.sty']

            ```
        - A missing directory is reported and nothing is removed:
            ```python
            >>> from pathlib import Path
            >>> from ddocs.latex.clean import clean_latex_build_files
            >>> clean_latex_build_files(Path("does-not-exist-dir"))
            Error: Directory not found: does-not-exist-dir
            0

            ```

    See Also:
        clean_latex_cli: Command-line wrapper around this function.
        ddocs.templates.repo_cloner.clone_repo_cli: Downloads the template files removed by ``templates=True``.
    """
    removed_count = 0
    if not directory.exists():
        print(f"Error: Directory not found: {directory}")
    elif not directory.is_dir():
        print(f"Error: Path is not a directory: {directory}")
    else:
        if pattern is not None:
            warnings.warn(
                "The 'pattern' argument of clean_latex_build_files is deprecated; use 'recursive' instead.",
                DeprecationWarning,
                stacklevel=2,
            )
        if recursive is None:
            recursive = True if pattern is None else pattern == "**/*"
        candidates = directory.glob("**/*" if recursive else "*")
        for file_path in sorted(p for p in candidates if _is_build_file(p)):
            removed_count += _remove_file(file_path, directory)

        if templates:
            for template_pattern in TEMPLATE_FILE_PATTERNS:
                for file_path in sorted(p for p in directory.glob(template_pattern) if p.is_file()):
                    removed_count += _remove_file(file_path, directory)
            pictures_dir = directory / TEMPLATE_PICTURES_DIR
            if pictures_dir.is_dir():
                removed_count += _remove_template_pictures(pictures_dir, directory)

    return removed_count


def clean_latex_cli(args: argparse.Namespace) -> int:
    """CLI interface for cleaning LaTeX build files.

    Args:
        args: Parsed arguments with ``directory``, ``recursive`` and (optionally) ``templates``.

    Returns:
        0 on success, 1 when the directory is missing or is not a directory.

    Examples:
        - Clean a directory and read the exit code:
            ```python
            >>> import argparse
            >>> import tempfile
            >>> from pathlib import Path
            >>> from ddocs.latex.clean import clean_latex_cli
            >>> with tempfile.TemporaryDirectory() as tmp:
            ...     (Path(tmp) / "doc.log").touch()
            ...     args = argparse.Namespace(directory=Path(tmp), recursive=False, templates=False)
            ...     clean_latex_cli(args)
            Cleaning LaTeX build files from: ...
            Removed: doc.log
            Cleaned 1 item(s)
            0

            ```
        - A missing directory gives exit code 1:
            ```python
            >>> import argparse
            >>> from pathlib import Path
            >>> from ddocs.latex.clean import clean_latex_cli
            >>> clean_latex_cli(argparse.Namespace(directory=Path("nope-dir"), recursive=False))
            Error: Directory not found: nope-dir
            1

            ```

    See Also:
        clean_latex_build_files: The function this CLI handler calls.
    """
    if not args.directory.exists():
        print(f"Error: Directory not found: {args.directory}")
        exit_code = 1
    elif not args.directory.is_dir():
        print(f"Error: Path is not a directory: {args.directory}")
        exit_code = 1
    else:
        print(f"Cleaning LaTeX build files from: {args.directory}")

        removed_count = clean_latex_build_files(
            args.directory, templates=getattr(args, "templates", False), recursive=args.recursive
        )

        if removed_count > 0:
            print(f"Cleaned {removed_count} item(s)")
        else:
            print("No LaTeX build files found to clean")
        exit_code = 0

    return exit_code
