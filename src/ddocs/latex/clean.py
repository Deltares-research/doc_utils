"""Remove LaTeX build artifacts (``.aux``, ``.log``, ``.bbl``, ...) from a directory.

Backs the ``ddocs clean`` command. This is independent of the Markdown-to-LaTeX
conversion -- it only deletes the throwaway files a LaTeX/BibTeX run leaves behind and,
when asked (``--templates``), the Deltares template files that ``ddocs get-tex-template``
downloads next to the document.
"""

import argparse
import re
import shutil
from pathlib import Path

# LaTeX build file extensions removed by default.
LATEX_BUILD_EXTENSIONS: tuple[str, ...] = (
    ".aux",  # Auxiliary file
    ".log",  # Log file
    ".bbl",  # Bibliography file (bibtex output)
    ".blg",  # Bibliography log file
    ".bcf",  # biblatex control file
    ".run.xml",  # biblatex/biber run file
    ".toc",  # Table of contents
    ".lof",  # List of figures
    ".lot",  # List of tables
    ".lol",  # List of listings
    ".loe",  # List of exercises
    ".tdo",  # todonotes list
    ".fdb_latexmk",  # latexmk file database
    ".fls",  # File list (latex -recorder)
    ".synctex.gz",  # SyncTeX file
    ".out",  # Hyperref outline
    ".nav",  # Beamer navigation
    ".snm",  # Beamer slide notes
    ".vrb",  # Beamer verbatim
    ".idx",  # Index file
    ".ilg",  # Index log
    ".ind",  # Index output
    ".xdy",  # xindy index style
    ".nlo",  # nomencl nomenclature list
    ".nls",  # nomencl sorted nomenclature
    ".nlg",  # nomencl log
    ".glo",  # glossary list
    ".gls",  # glossary output
    ".glg",  # glossary log
    ".maf",  # minitoc auxiliary file list
    ".mtc",  # minitoc mini table of contents
)

# minitoc writes one numbered file per mini table of contents: .mtc0, .mtc1, ...
_MINITOC_NUMBERED = re.compile(r"\.mtc\d+$")

# Files fetched by ``ddocs get-tex-template`` (Deltares classes, styles, bib and makeindex styles).
TEMPLATE_FILE_PATTERNS: tuple[str, ...] = (
    "deltares_*.cls",
    "deltares_*.sty",
    "deltares_*.bst",
    "deltares_*.ist",
)

# Directories fetched by ``ddocs get-tex-template`` (looked up directly under the cleaned directory).
TEMPLATE_DIRECTORIES: tuple[str, ...] = ("pictures",)


def _is_build_file(path: Path) -> bool:
    """Return True when `path` is a regular file with a LaTeX build-artifact extension."""
    name = path.name.lower()
    return path.is_file() and (name.endswith(LATEX_BUILD_EXTENSIONS) or _MINITOC_NUMBERED.search(name) is not None)


def _remove_file(file_path: Path, directory: Path) -> int:
    """Delete one file, report it, and return 1 on success or 0 when it could not be removed."""
    try:
        file_path.unlink()
        print(f"Removed: {file_path.relative_to(directory)}")
        removed = 1
    except OSError as e:
        print(f"Warning: Could not remove {file_path}: {e}")
        removed = 0
    return removed


def _remove_template_directory(template_dir: Path, directory: Path) -> int:
    """Delete a downloaded template directory and return the number of files it held."""
    file_count = sum(1 for p in template_dir.rglob("*") if p.is_file())
    try:
        shutil.rmtree(template_dir)
        print(f"Removed: {template_dir.relative_to(directory)}/ ({file_count} file(s))")
        removed = file_count
    except OSError as e:
        print(f"Warning: Could not remove {template_dir}: {e}")
        removed = 0
    return removed


def clean_latex_build_files(directory: Path, pattern: str = "**/*", templates: bool = False) -> int:
    """Clean LaTeX build artifacts (and optionally downloaded templates) from a directory.

    Removes the files generated by pdflatex, bibtex, makeindex, minitoc, nomencl and
    related tools -- see :data:`LATEX_BUILD_EXTENSIONS` -- plus numbered ``.mtcN`` files.
    Source files (``.tex``) and the produced ``.pdf`` are never touched.

    Args:
        directory: Directory to clean
        pattern: Glob pattern for subdirectories to include (default: "**/*" for recursive)
        templates: When True, also remove the files ``ddocs get-tex-template`` downloads:
            ``deltares_*.cls/.sty/.bst/.ist`` (in `directory`, or below it when recursive) and the
            ``pictures/`` directory directly under `directory`. Defaults to False.

    Returns:
        Number of files removed

    Examples:
        - Remove the build artifacts next to a document:
            ```python
            >>> import tempfile
            >>> from pathlib import Path
            >>> from ddocs.latex.clean import clean_latex_build_files
            >>> with tempfile.TemporaryDirectory() as tmp:
            ...     (Path(tmp) / "doc.tex").touch()
            ...     (Path(tmp) / "doc.aux").touch()
            ...     clean_latex_build_files(Path(tmp), pattern="*")
            Removed: doc.aux
            1

            ```
    """
    removed_count = 0
    if not directory.exists():
        print(f"Error: Directory not found: {directory}")
    elif not directory.is_dir():
        print(f"Error: Path is not a directory: {directory}")
    else:
        recursive = pattern == "**/*"
        candidates = directory.glob("**/*" if recursive else "*")
        for file_path in sorted(p for p in candidates if _is_build_file(p)):
            removed_count += _remove_file(file_path, directory)

        if templates:
            for template_pattern in TEMPLATE_FILE_PATTERNS:
                glob_pattern = f"**/{template_pattern}" if recursive else template_pattern
                for file_path in sorted(p for p in directory.glob(glob_pattern) if p.is_file()):
                    removed_count += _remove_file(file_path, directory)
            for dir_name in TEMPLATE_DIRECTORIES:
                template_dir = directory / dir_name
                if template_dir.is_dir():
                    removed_count += _remove_template_directory(template_dir, directory)

    return removed_count


def clean_latex_cli(args: argparse.Namespace) -> int:
    """CLI interface for cleaning LaTeX build files.

    Args:
        args: Parsed arguments with ``directory``, ``recursive`` and (optionally) ``templates``.

    Returns:
        0 on success, 1 when the directory is missing or is not a directory.
    """
    if not args.directory.exists():
        print(f"Error: Directory not found: {args.directory}")
        exit_code = 1
    elif not args.directory.is_dir():
        print(f"Error: Path is not a directory: {args.directory}")
        exit_code = 1
    else:
        print(f"Cleaning LaTeX build files from: {args.directory}")

        pattern = "**/*" if args.recursive else "*"
        removed_count = clean_latex_build_files(
            args.directory, pattern, templates=getattr(args, "templates", False)
        )

        if removed_count > 0:
            print(f"Cleaned {removed_count} LaTeX build file(s)")
        else:
            print("No LaTeX build files found to clean")
        exit_code = 0

    return exit_code
